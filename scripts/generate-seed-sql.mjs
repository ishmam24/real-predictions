// Builds supabase/seed.sql (reference-data INSERTs) and supabase/setup.sql
// (the full schema + seed you paste into the Supabase SQL Editor once).
//
// The reference data is read straight from src/lib/mock-data.ts, which is
// itself generated from the live FPL API by scripts/generate-pl-data.mjs. So
// the live database ships with the real current-season clubs, squads, and the
// current gameweek's fixtures on day one.
//
// Run with Node 22+:  node --experimental-strip-types scripts/generate-seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { teams, players, fixtures, gameweeks } from "../src/lib/mock-data.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// --- SQL literal helpers ----------------------------------------------------
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? "null" : String(v));

// --- Build the seed statements ----------------------------------------------
const lines = [];
lines.push("-- ============================================================");
lines.push("-- Seed: reference data (teams, squads, current gameweek + fixtures)");
lines.push("-- Generated by scripts/generate-seed-sql.mjs — do not edit by hand.");
lines.push("-- Safe to re-run: upserts on primary key.");
lines.push("-- ============================================================");
lines.push("");

lines.push("insert into public.teams (id, name, short_name, tla, color, crest_url) values");
lines.push(
  teams
    .map((t) => `  (${q(t.id)}, ${q(t.name)}, ${q(t.name)}, ${q(t.tla)}, ${q(t.color)}, ${q(t.crestUrl)})`)
    .join(",\n") +
    "\non conflict (id) do update set name = excluded.name, short_name = excluded.short_name, tla = excluded.tla, color = excluded.color, crest_url = excluded.crest_url;",
);
lines.push("");

lines.push("insert into public.players (id, team_id, name, position) values");
lines.push(
  players
    .map((p) => `  (${q(p.id)}, ${q(p.teamId)}, ${q(p.name)}, ${q(p.position)})`)
    .join(",\n") +
    "\non conflict (id) do update set team_id = excluded.team_id, name = excluded.name, position = excluded.position;",
);
lines.push("");

lines.push("insert into public.gameweeks (id, number, title, deadline, status) values");
lines.push(
  gameweeks
    .map((gw) => `  (${q(gw.id)}, ${n(gw.number)}, ${q(gw.title)}, ${q(gw.deadline)}, ${q(gw.status)})`)
    .join(",\n") +
    "\non conflict (id) do update set number = excluded.number, title = excluded.title, deadline = excluded.deadline, status = excluded.status;",
);
lines.push("");

lines.push(
  "insert into public.fixtures (id, external_id, gameweek_id, home_team_id, away_team_id, kickoff_time, status, home_score, away_score, potm_player_id) values",
);
lines.push(
  fixtures
    .map(
      (f) =>
        `  (${q(f.id)}, ${n(f.externalId)}, ${q(f.gameweekId)}, ${q(f.homeTeamId)}, ${q(f.awayTeamId)}, ${q(f.kickoff)}, ${q(f.status)}, ${n(f.homeScore)}, ${n(f.awayScore)}, ${q(f.potmPlayerId)})`,
    )
    .join(",\n") +
    "\non conflict (id) do update set external_id = excluded.external_id, gameweek_id = excluded.gameweek_id, home_team_id = excluded.home_team_id, away_team_id = excluded.away_team_id, kickoff_time = excluded.kickoff_time;",
);
lines.push("");

const seed = lines.join("\n");
writeFileSync(join(root, "supabase", "seed.sql"), seed + "\n");

// --- Combine migrations + seed into a single paste-me file ------------------
const migrations = ["0001_schema.sql", "0002_scoring.sql", "0003_rls.sql", "0004_intro_onboarding.sql"];
const parts = [
  "-- ============================================================================",
  "-- Real Predictions — full database setup.",
  "-- Paste this whole file into the Supabase dashboard → SQL Editor → Run.",
  "-- Generated by scripts/generate-seed-sql.mjs (schema migrations + seed).",
  "-- ============================================================================",
  "",
  "-- ----------------------------------------------------------------------------",
  "-- RESET: drop our objects first so this file is safely re-runnable. Safe while",
  "-- there is no real data yet; remove this block once players have signed up.",
  "-- ----------------------------------------------------------------------------",
  "drop trigger if exists on_auth_user_created on auth.users;",
  "drop table if exists public.predictions cascade;",
  "drop table if exists public.league_members cascade;",
  "drop table if exists public.leagues cascade;",
  "drop table if exists public.fixtures cascade;",
  "drop table if exists public.players cascade;",
  "drop table if exists public.gameweeks cascade;",
  "drop table if exists public.profiles cascade;",
  "drop table if exists public.teams cascade;",
  "drop view if exists public.leaderboard cascade;",
  "drop type if exists public.gameweek_status cascade;",
  "drop type if exists public.fixture_status cascade;",
  "drop function if exists public.handle_new_user() cascade;",
  "drop function if exists public.match_outcome(int, int) cascade;",
  "drop function if exists public.settle_fixture(text) cascade;",
  "drop function if exists public.unsettle_fixture(text) cascade;",
  "drop function if exists public.league_leaderboard(uuid) cascade;",
  "drop function if exists public.is_admin() cascade;",
  "drop function if exists public.fixture_deadline_passed(text) cascade;",
  "drop function if exists public.fixture_deadline_passed(uuid) cascade;",
  "drop function if exists public.is_league_member(uuid, uuid) cascade;",
  "drop function if exists public.create_league(text) cascade;",
  "drop function if exists public.join_league_by_code(text) cascade;",
  "",
];
for (const m of migrations) {
  parts.push(`-- ============================================================`);
  parts.push(`-- supabase/migrations/${m}`);
  parts.push(`-- ============================================================`);
  parts.push(readFileSync(join(root, "supabase", "migrations", m), "utf8").trimEnd());
  parts.push("");
}
parts.push(seed.trimEnd());
parts.push("");
parts.push("-- ---------------------------------------------------------------------------");
parts.push("-- ONE-TIME ADMIN BOOTSTRAP: after you sign up in the app, run ONE of these");
parts.push("-- (while signed in as yourself) to unlock the admin panel:");
parts.push("--   update public.profiles set is_admin = true where id = auth.uid();");
parts.push("--   update public.profiles set is_admin = true where display_name = 'YOUR NAME';");
parts.push("-- ---------------------------------------------------------------------------");
parts.push("");

writeFileSync(join(root, "supabase", "setup.sql"), parts.join("\n"));

console.log(
  `Wrote supabase/seed.sql and supabase/setup.sql — ${teams.length} teams, ${players.length} players, ${fixtures.length} fixtures, gameweeks ${gameweeks.map((g) => g.id).join(", ")}.`,
);
